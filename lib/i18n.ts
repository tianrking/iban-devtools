const messages: Record<AppLocale, Messages> = {
  en,
  es,
  fr,
  ar,
  "zh-TW": zhTW,
  "zh-CN": zhCN,
};

const displayNamesCache = new Map<AppLocale, Intl.DisplayNames>();
const numberFormatCache = new Map<AppLocale, Intl.NumberFormat>();

const KOSOVO_NAMES: Record<AppLocale, string> = {
  en: "Kosovo",
  es: "Kosovo",
  fr: "Kosovo",
  ar: "كوسوفو",
  "zh-TW": "科索沃",
  "zh-CN": "科索沃",
};

export type Translate = (
  key: MessageKey,
  values?: Record<string, string | number>,
) => string;

export function isAppLocale(value: unknown): value is AppLocale {
  return (
    typeof value === "string" &&
    (SUPPORTED_LOCALES as readonly string[]).includes(value)
  );
}

export function resolveAppLocale(
  urlLocale: unknown,
  storedLocale: unknown,
): AppLocale {
  if (isAppLocale(urlLocale)) return urlLocale;
  if (isAppLocale(storedLocale)) return storedLocale;
  return DEFAULT_LOCALE;
}

export function localeDirection(locale: AppLocale): TextDirection {
  return locale === "ar" ? "rtl" : "ltr";
}

export function createTranslator(locale: AppLocale): Translate {
  return (key, values = {}) => {
    let message = messages[locale][key];
    for (const [name, value] of Object.entries(values)) {
      message = message.replaceAll(`{${name}}`, String(value));
    }
    return message;
  };
}

export function formatLocaleNumber(
  value: number,
  locale: AppLocale,
): string {
  let formatter = numberFormatCache.get(locale);
  if (!formatter) {
    formatter = new Intl.NumberFormat(locale);
    numberFormatCache.set(locale, formatter);
  }
  return formatter.format(value);
}

export function displayCountryName(
  countryCode: string,
  locale: AppLocale,
  fallback = countryCode,
): string {
  const code = countryCode.toUpperCase();
  if (code === "XK") return KOSOVO_NAMES[locale];
  try {
    let formatter = displayNamesCache.get(locale);
    if (!formatter) {
      formatter = new Intl.DisplayNames([locale], {
        type: "region",
        fallback: "none",
      });
      displayNamesCache.set(locale, formatter);
    }
    return formatter.of(code) ?? fallback;
  } catch {
    return fallback;
  }
}

export function getMessages(locale: AppLocale): Readonly<Messages> {
  return messages[locale];
}

